"""The 30-day variance risk premium on BTC and ETH, 2021–2026: Deribit's DVOL index (30-day
constant-maturity implied vol) against the realised vol of the following 30 days.

    python -m vr.spot --start 2021-01-01 && python -m vr.deribit dvol
    python scripts/run_vrp.py

Writes reports/vrp/: series_<CCY>.csv (daily), summary.csv (by year and currency), the
distribution plot, and note_autogen.md. notes/01_vrp.md is hand-written.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from vr.spot import load_close
from vr.store import read_range
from vr.vol import vrp

START, END = "2021-03-24", pd.Timestamp.now(tz="UTC").strftime("%Y-%m-%d")
OUT = Path("reports/vrp"); OUT.mkdir(parents=True, exist_ok=True)
SYMBOL = {"BTC": "BTCUSDT", "ETH": "ETHUSDT"}


def load(ccy: str):
    dv = read_range("raw", "deribit", "dvol_1h", ccy, START, END)
    close = load_close(SYMBOL[ccy], "2021-01-01", END)
    return dv["close"].rename("dvol"), close


def stats(d: pd.DataFrame) -> dict:
    v = d["vrp"].dropna()
    return {"days": int(len(v)), "iv_mean": float(d["iv"].mean()), "rv_next_mean": float(d["rv_next"].mean()),
            "vrp_mean": float(v.mean()), "vrp_median": float(v.median()), "vrp_p10": float(v.quantile(0.1)),
            "vrp_p90": float(v.quantile(0.9)), "share_positive": float((v > 0).mean()),
            "worst": float(v.min()), "worst_date": str(v.idxmin().date()) if len(v) else "",
            "vrp_var_mean": float(d["vrp_var"].dropna().mean())}


def main():
    rows, series = [], {}
    fig, axes = plt.subplots(2, 2, figsize=(13, 8))
    for i, ccy in enumerate(("BTC", "ETH")):
        dvol, close = load(ccy)
        d = vrp(dvol, close, 30)
        daily = d.resample("D").last()                              # one observation a day, at 00:00 UTC
        daily.to_csv(OUT / f"series_{ccy}.csv"); series[ccy] = daily
        for yr, g in daily.groupby(daily.index.year):
            rows.append({"ccy": ccy, "year": int(yr), **stats(g)})
        rows.append({"ccy": ccy, "year": "all", **stats(daily)})
        ax = axes[0, i]; ax.plot(daily.index, daily["iv"], lw=0.8, label="DVOL (30d implied)")
        ax.plot(daily.index, daily["rv_next"], lw=0.8, label="realised, next 30d"); ax.set_title(f"{ccy}: implied vs realised, vol pts"); ax.legend(fontsize=8)
        ax = axes[1, i]; v = daily["vrp"].dropna()
        ax.hist(v, bins=60, alpha=0.8); ax.axvline(0, color="k", lw=0.8); ax.axvline(v.median(), color="r", lw=0.8)
        ax.set_title(f"{ccy}: VRP = IV − next-30d RV; median {v.median():.1f}, positive {100 * (v > 0).mean():.0f}% of days")
    fig.tight_layout(); fig.savefig(OUT / "vrp.png", dpi=120)
    summary = pd.DataFrame(rows); summary.to_csv(OUT / "summary.csv", index=False)
    pd.set_option("display.width", 220); print(summary.round(2).to_string(index=False))
    # persistence: how long does a negative VRP (realised > implied) last once it starts?
    lines = []
    for ccy, daily in series.items():
        neg = (daily["vrp"] < 0).astype(int)
        spells = neg.groupby((neg != neg.shift()).cumsum()).sum(); spells = spells[spells > 0]
        lines.append(f"{ccy}: {len(spells)} negative spells, median {spells.median():.0f} days, max {spells.max():.0f} days")
    print("\n".join(lines))
    (OUT / "note_autogen.md").write_text("# VRP (autogenerated)\n\n" + summary.round(2).to_string(index=False) + "\n\n" + "\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
