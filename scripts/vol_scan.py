"""Today's BTC/ETH option surface: Deribit term structure and skew, and the IV gap between Deribit
and Derive (on-chain) per matched option, with open interest on each side.

    python -m vr.deribit book && python -m vr.derive book
    python scripts/vol_scan.py

Writes reports/scan/: surface_<CCY>_<venue>.csv, gap_<CCY>.csv, surface.png, note_autogen.md.
Snapshot, dated; nothing here is a backtest.
"""
from __future__ import annotations

import glob
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from vr.store import ROOT
from vr.vol import surface_summary, venue_gap

OUT = Path("reports/scan"); OUT.mkdir(parents=True, exist_ok=True)


def latest(venue: str, ccy: str) -> pd.DataFrame | None:
    fs = sorted(glob.glob(str(ROOT / "processed" / venue / f"book_{ccy}_*.csv")))
    if not fs:
        return None
    df = pd.read_csv(fs[-1], parse_dates=["expiry", "snapshot_ts"])
    df["expiry"] = pd.to_datetime(df["expiry"], utc=True)
    return df


def main():
    md = ["# Surface scan (autogenerated)", ""]
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.5))
    for i, ccy in enumerate(("BTC", "ETH")):
        der = latest("deribit", ccy); drv = latest("derive", ccy)
        if der is None:
            print(f"{ccy}: no Deribit book"); continue
        s_der = surface_summary(der); s_der.to_csv(OUT / f"surface_{ccy}_deribit.csv", index=False)
        md += [f"## {ccy} Deribit, {der['snapshot_ts'].iloc[0]:%Y-%m-%d %H:%M} UTC, spot {der['underlying_price'].median():,.0f}",
               s_der.round(1).to_string(index=False), ""]
        ax = axes[i]; ax.plot(s_der["tenor_days"], s_der["atm_iv"], marker="o", ms=3, label="Deribit ATM")
        ax.plot(s_der["tenor_days"], s_der["iv_25d_put"], marker=".", ms=3, lw=0.8, label="Deribit 25d put")
        ax.plot(s_der["tenor_days"], s_der["iv_25d_call"], marker=".", ms=3, lw=0.8, label="Deribit 25d call")
        if drv is not None and len(drv):
            s_drv = surface_summary(drv); s_drv.to_csv(OUT / f"surface_{ccy}_derive.csv", index=False)
            ax.plot(s_drv["tenor_days"], s_drv["atm_iv"], marker="s", ms=3, ls="--", label="Derive ATM")
            gap = venue_gap(der, drv, "deribit", "derive"); gap.to_csv(OUT / f"gap_{ccy}.csv", index=False)
            if len(gap):
                by = gap.assign(bucket=pd.cut(gap["abs_delta"], [0, 0.15, 0.35, 0.65, 1.0], labels=["wing", "25d", "atm", "itm"]))
                g = by.groupby(["bucket", "type"], observed=True).agg(n=("gap_vol_pts", "size"), gap_median=("gap_vol_pts", "median"),
                                                                       gap_p90=("gap_vol_pts", lambda x: x.quantile(0.9)),
                                                                       oi_derive_usd=("oi_derive", "sum"))
                md += [f"## {ccy} Derive minus Deribit, vol points, {len(gap)} matched options", g.round(2).to_string(),
                       f"Derive total OI (contracts): {drv['open_interest'].sum():,.1f}; Deribit: {der['open_interest'].sum():,.0f}", ""]
                print(f"{ccy}: {len(gap)} matched; median gap {gap['gap_vol_pts'].median():+.2f} vol pts")
        ax.set_xscale("log"); ax.set_xlabel("days to expiry"); ax.set_ylabel("IV, vol pts"); ax.set_title(ccy); ax.legend(fontsize=7); ax.grid(alpha=0.3)
    fig.tight_layout(); fig.savefig(OUT / "surface.png", dpi=120)
    (OUT / "note_autogen.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
