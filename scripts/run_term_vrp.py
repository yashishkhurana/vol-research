"""Variance risk premium at 30, 90, 180, 270 and 365 days, from daily Deribit option prices.

Does selling longer-dated vol earn more than selling 30-day vol? For every day since 2023, rebuild
constant-maturity ATM implied vol at each tenor from traded option prices (vr/term.py), then
compare it with the realised vol of the following h days (Binance hourly closes). A tenor's VRP
exists only where the forward window has fully happened: the 365-day one ends a year before today.

    python -m vr.spot --start 2021-01-01 && python -m vr.deribit dvol      # realised vol, DVOL check
    python scripts/run_term_vrp.py

Writes reports/vrp/: term_<CCY>.csv (daily ATM IV and VRP per tenor), atm_by_expiry_<CCY>.csv,
term_summary.csv (by year and tenor), term.png, term_note_autogen.md.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from vr.spot import load_close
from vr.store import read_range
from vr.term import build, constant_maturity, futures_cache
from vr.vol import realised_vol

OUT = Path("reports/vrp"); OUT.mkdir(parents=True, exist_ok=True)
SYMBOL = {"BTC": "BTCUSDT", "ETH": "ETHUSDT"}
TENORS = (30, 90, 180, 270, 365)                      # 365 is rarely bracketed: see the note
END = pd.Timestamp.now(tz="UTC").strftime("%Y-%m-%d")


def term_table(ccy: str) -> tuple[pd.DataFrame, pd.DataFrame]:
    fut = futures_cache(ccy)
    opt, atm = build(ccy, fut)
    atm.to_csv(OUT / f"atm_by_expiry_{ccy}.csv", index=False)
    cm = constant_maturity(atm, TENORS)
    cm.index = pd.DatetimeIndex(cm.index) + pd.Timedelta(hours=32)       # stamped at the candle close
    close = load_close(SYMBOL[ccy], "2021-01-01", END)              # forward RV needs a full window of history behind t too
    for h in TENORS:
        rv = realised_vol(close, h, forward=True).reindex(cm.index)
        cm[f"rv_next_{h}d"] = rv
        cm[f"vrp_{h}d"] = cm[f"atm_{h}d"] - rv
    dv = read_range("raw", "deribit", "dvol_1h", ccy, "2023-01-01", END)
    if not dv.empty:
        cm["dvol"] = dv["close"].reindex(cm.index)
    cm.index.name = "asof"
    cm.to_csv(OUT / f"term_{ccy}.csv")
    stats = {"options_traded_rows": len(opt), "with_iv": int(opt["iv"].notna().sum()),
             "atm_points": len(atm), "days": len(cm)}
    return cm, pd.DataFrame([stats])


def summary(cm: pd.DataFrame, ccy: str) -> list[dict]:
    rows = []
    for h in TENORS:
        d = cm[[f"atm_{h}d", f"rv_next_{h}d", f"vrp_{h}d"]].dropna()
        for yr, g in [*d.groupby(d.index.year), ("all", d)]:
            v = g[f"vrp_{h}d"]
            if v.empty:
                continue
            rows.append({"ccy": ccy, "tenor_days": h, "year": yr, "days": len(v),
                         "independent_windows": round(len(v) / h, 1),
                         "atm_iv_mean": g[f"atm_{h}d"].mean(), "rv_next_mean": g[f"rv_next_{h}d"].mean(),
                         "vrp_mean": v.mean(), "vrp_median": v.median(), "vrp_p10": v.quantile(0.1),
                         "share_positive": (v > 0).mean(), "first": str(v.index.min().date()), "last": str(v.index.max().date())})
    return rows


def main():
    rows, md = [], ["# Term-structure VRP (autogenerated)", ""]
    fig, axes = plt.subplots(2, 2, figsize=(14, 8))
    for i, ccy in enumerate(("BTC", "ETH")):
        cm, st = term_table(ccy)
        rows += summary(cm, ccy)
        cov = {h: f"{cm[f'atm_{h}d'].notna().mean():.0%}" for h in TENORS}
        md += [f"## {ccy}", f"pipeline: {st.to_dict('records')[0]}", f"days with each tenor (no extrapolation): {cov}"]
        if "dvol" in cm:
            d = cm[["atm_30d", "dvol"]].dropna()
            md.append(f"check vs DVOL (30d, includes skew): {len(d)} days, mean DVOL - ATM30 = {(d['dvol'] - d['atm_30d']).mean():+.2f} vol pts, "
                      f"median {(d['dvol'] - d['atm_30d']).median():+.2f}, correlation {d['dvol'].corr(d['atm_30d']):.3f}")
        md.append("")
        ax = axes[0, i]
        for h in TENORS:
            ax.plot(cm.index, cm[f"atm_{h}d"], lw=0.8, label=f"ATM {h}d")
        ax.set_title(f"{ccy}: constant-maturity ATM IV, vol pts"); ax.legend(fontsize=8); ax.grid(alpha=0.3)
        ax = axes[1, i]
        for h in TENORS:
            ax.plot(cm.index, cm[f"vrp_{h}d"], lw=0.8, label=f"VRP {h}d")
        ax.axhline(0, color="k", lw=0.6); ax.set_title(f"{ccy}: ATM IV minus realised vol of the next h days"); ax.legend(fontsize=8); ax.grid(alpha=0.3)
    fig.tight_layout(); fig.savefig(OUT / "term.png", dpi=120)
    s = pd.DataFrame(rows); s.to_csv(OUT / "term_summary.csv", index=False)
    pd.set_option("display.width", 250)
    allrows = s[s["year"] == "all"]
    md += ["## All years", allrows.round(2).to_string(index=False), "", "## By year", s[s["year"] != "all"].round(2).to_string(index=False)]
    (OUT / "term_note_autogen.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
